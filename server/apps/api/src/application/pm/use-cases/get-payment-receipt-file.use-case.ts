import { Inject, Injectable, NotFoundException, ForbiddenException } from '@nestjs/common';
import { IPropertyRepository, PM_PROPERTY_REPOSITORY } from '../../../domains/pm/IPropertyRepository';
import { PrismaService } from '../../../shared/infrastructure/prisma/prisma.service';
import { S3Service } from '../../../shared/infrastructure/common/s3/s3.service';
import { GenerateReceiptPdfUseCase } from '../../use-cases/payments/generate-receipt-pdf.use-case';
import { EncryptionService } from '../../../shared/infrastructure/common/encryption.service';

export interface GetPaymentReceiptFileDto {
  pmId: number;
  paymentUuid: string;
  unitUuid: string;
  actor?: any;
  res: any;
}

@Injectable()
export class GetPaymentReceiptFileUseCase {
  constructor(
    private readonly prisma: PrismaService,
    private readonly s3Service: S3Service,
    @Inject(PM_PROPERTY_REPOSITORY)
    private readonly propertyRepository: IPropertyRepository,
    private readonly generateReceiptPdfUseCase: GenerateReceiptPdfUseCase,
    private readonly encryption: EncryptionService,
  ) {}

  async execute(dto: GetPaymentReceiptFileDto) {
    const { pmId, paymentUuid, unitUuid, actor, res } = dto;
    const ownerPmId = actor ? actor.ownerPmId : pmId;

    const payment = await this.prisma.upward_pm_rent_payment.findUnique({
      where: { uuid: paymentUuid },
      include: {
        unit: {
          include: {
            property: true,
          },
        },
      },
    });

    if (!payment || payment.unit.uuid !== unitUuid) {
      throw new NotFoundException('Rent record not found');
    }

    const hasAccess = await this.propertyRepository.hasAccessToProperty(ownerPmId, payment.unit.property.id, actor);
    if (!hasAccess) {
      throw new ForbiddenException('You do not have access to this unit');
    }

    const p = payment as any;
    // 1. If an S3 manual upload exists (not auto-generated by Upward receipt generator), redirect directly
    if (p.receiptUrl && !p.receiptUrl.includes('/upward_receipt_')) {
      const downloadUrl = await this.s3Service.getDownloadUrl(p.receiptUrl);

      if (res && typeof res.redirect === 'function') {
        return res.redirect(downloadUrl, 302);
      }

      return {
        downloadUrl,
        fileName: p.receiptFileName || 'receipt',
      };
    }

    // 2. Resolve matching transaction strictly for this payment's reference (payment.reference == tx.reference)
    let tx: any = null;
    if (payment.reference) {
      tx = await this.prisma.upward_transaction.findFirst({
        where: { reference: payment.reference },
        include: {
          paymentRequest: true,
          user: true,
        },
      });
    }

    if (!tx) {
      throw new NotFoundException('No receipt exists for this payment record');
    }

    const userProperty = await this.prisma.upward_user_property.findFirst({
      where: { pmUnitId: payment.unit.id },
    });

    const tenant = payment.tenantId
      ? await this.prisma.upward_pm_tenant.findUnique({
          where: { id: payment.tenantId },
        })
      : null;
    const tenantFirstName = tenant?.firstNameEncrypted
      ? this.encryption.decrypt(tenant.firstNameEncrypted)
      : (tx.user?.firstName ? this.encryption.decrypt(tx.user.firstName) : '');
    const tenantLastName = tenant?.lastNameEncrypted
      ? this.encryption.decrypt(tenant.lastNameEncrypted)
      : (tx.user?.lastName ? this.encryption.decrypt(tx.user.lastName) : '');
    const tenantName = `${tenantFirstName} ${tenantLastName}`.trim() || 'Tenant';

    const rentStartDate = payment.periodStart || (tx as any)?.rentStartDate;
    const rentEndDate = payment.periodEnd || (tx as any)?.rentEndDate;
    const tenancyPeriod =
      rentStartDate && rentEndDate
        ? `${new Date(rentStartDate).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })} - ${new Date(rentEndDate).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })}`
        : undefined;

    const receiptPayload = {
      title: 'Rent Payment Receipt',
      receiptNumber: `RCP-${tx.reference.slice(-5).toUpperCase()}`,
      paidAt: tx.createdAt ? new Date(tx.createdAt) : new Date(payment.paymentDate),
      tenantName,
      propertyAddress:
        payment.unit.property.address ||
        payment.unit.property.name,
      propertyName: payment.unit.property.name,
      amount: tx.amount,
      currency: tx.currency || 'NGN',
      reference: tx.reference,
      channel: tx.isManual
        ? 'Bank Transfer'
        : payment.method === 'PAYSTACK'
          ? 'Paystack'
          : payment.method || 'Bank Transfer',
      type: 'RENT',
      status: 'PAID',
      rentStartDate: rentStartDate ? new Date(rentStartDate) : undefined,
      rentEndDate: rentEndDate ? new Date(rentEndDate) : undefined,
      tenancyPeriod,
      userPropertyId: userProperty?.id,
      companyName: payment.unit.property.name,
    };

    const pdfBuffer = await this.generateReceiptPdfUseCase.executeBuffer(receiptPayload);

    // Cache generated PDF in S3 for future instant downloads
    const s3Key = `pm-docs/receipts/pm_${ownerPmId}/upward_receipt_${payment.uuid}.pdf`;
    await this.s3Service.uploadBuffer(pdfBuffer, s3Key, 'application/pdf');

    const fileName = `upward_receipt_${payment.amount}.pdf`;
    await this.prisma.upward_pm_rent_payment.update({
      where: { id: payment.id },
      data: {
        receiptUrl: s3Key,
        receiptFileName: fileName,
        receiptFileType: 'application/pdf',
        receiptFileSize: pdfBuffer.length,
        reference: tx.reference,
      },
    });

    const downloadUrl = await this.s3Service.getDownloadUrl(s3Key);

    if (res && typeof res.redirect === 'function') {
      return res.redirect(downloadUrl, 302);
    }

    return {
      downloadUrl,
      fileName,
    };
  }
}
